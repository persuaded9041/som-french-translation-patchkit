; Secret of Mana (USA) — dialogue VWF continuous-cursor renderer
; Documentation/source-map reference; build_patch.py is the canonical emitter.
; =====================================================
;
; Runtime-validated event scope:
;   $C0:1664 is shared by the event engine, GAME SELECT and another caller.
;   At $C0:167D the generated entry helper reads the untouched JSR return
;   address at 1,S. Only return $1152 (call from $C0:1150) plus event bank
;   $C9/$CA activates component 06. GAME SELECT returns as $235E and stays stock.
;   Component 05 intercepts translated intro event $0400 earlier at $C0:1664,
;   so component 06 never reaches this entry during that intro.
;
; Runtime-validated renderer:
;   keep stock $C0:168A-$16B0 code -> glyph lookup/render path intact;
;   128-entry advance table at $ED:7200;
;   space=$80 => 4 px advance;
;   lowercase a-z => framed ink width + 1 px black separator;
;   uppercase/punctuation/French framing and metrics as documented in README.md;
;   continuous cumulative pixel cursor with cross-cell merge/spill;
;   generic interrupted-chunk conversion before stock progression.
;
; $7E:9385 is the per-invocation component-06 active tag. It overlaps the intro
; renderer's glyph-advance scratch only because the two renderers are mutually
; exclusive: component 05 exits before $C0:167D for event $0400.
;
; The post-outline repair at $C0:1168 remains deliberately $C9-only pending a
; separate runtime audit for $CA; the core renderer itself is caller-gated C9/CA.

