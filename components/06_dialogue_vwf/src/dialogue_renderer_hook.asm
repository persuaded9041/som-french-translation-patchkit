org $C016A4
    jsl dialogue_font_row

org $C016B1
    jml dialogue_char_end
    nop #2

org $ED7040
dialogue_render_init:
    ; Generated byte-exactly by build_patch.py.

org $ED7180
dialogue_char_start:
    ; For $C9, snapshot physical chunk cells when X reaches the saved decoded
    ; count, then derive Y = floor(pixel_cursor/8)*12 and replay the untouched
    ; stock glyph-addressing path at $C0:168A.

org $ED70C0
dialogue_char_end:
    ; Read the current character's advance from the 128-entry table at
    ; $ED:7200, then reproduce the stock DEC $A176 / loop contract. On the
    ; final slot, continue at $ED:7340 for the generic interrupted-chunk commit
    ; before returning through stock $C0:16B7. Stock progression at $C0:13A3 is
    ; unmodified. A remains 8-bit.

org $ED7100
dialogue_font_row:
    ; Replays LDA.l $D2DC00,X. Framing is still applied at this validated
    ; point; only the lowercase range decision is factored to $ED:71B0.

org $ED71B0
dialogue_framing_selector:
    ; a-h/k/m-s/u-z = 1 px, i/l = 3 px, j/t = 2 px.
    ; Rows after z branch to the adjacent punctuation selector.
    ; No generic shift table and no new WRAM state.

org $ED71E8
dialogue_punctuation_framing_selector:
    ; Post-lowercase dispatch. The fixed JML trampoline remains exactly at
    ; $ED:71F4 and forwards A+ to the extended selector.

org $ED72F0
dialogue_punctuation_framing_batch2_selector:
    ; A-H/J-Z shift 1 px, I shifts 3 px (runtime-validated).
    ; $B5-$BE digits stay generic/stock. Runtime-validated punctuation is
    ; preserved; $CD-$D3 stay untouched. French runtime-validated: $D4-$E3 shift
    ; 1 px, while full-width $E4/$E5 remain unshifted.


